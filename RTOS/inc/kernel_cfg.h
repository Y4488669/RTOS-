#ifndef RTOS_KERNEL_CFG_H
#define RTOS_KERNEL_CFG_H

#include "debug.h"

/* ===========================================================================
 * 一、调度规模
 * =========================================================================*/

/* 优先级层数。就绪队列是"一层一条链表",所以这个数字 = 就绪链表的条数。
 * 数字越大优先级越高:0 是空闲任务的优先级,(CFG_PRIO_LEVELS - 1) 最高。
 * 注意和 ARM 中断优先级**正好相反**:那边数字越小优先级越高。
 * 选 8 是因为正好塞进一个字节的位图(其实 32 以内都只用一个 uint32_t)。*/
#define CFG_PRIO_LEVELS        8

/* 同时存在的任务上限。任务对象和它的栈都是静态数组,编译期就占好内存,
 * 永远不会失败、不会碎片、不需要 free —— 这是裸机 RTOS 的默认姿势。*/
#define CFG_MAX_TASKS          8

/* 任务栈深度,单位是"字"(uint32_t),不是字节。
 * 128 字 = 512 字节,够一个不做深度递归的普通任务用了。*/
#define CFG_STACK_WORDS        128

/* 空闲任务的栈可以小一点:它只做 wfi 和栈检查。*/
#define CFG_IDLE_STACK_WORDS   64

/* ===========================================================================
 * 二、时基
 * =========================================================================*/

/* 心跳频率:tick 每秒来多少次。1000 Hz 意味着 1 tick = 1 ms,
 * 这是绝大多数 RTOS 的默认值 —— 换算心算方便(delay(500) 就是 500ms)。
 *
 * 别学你 RTOS/ 里那个 1 秒一次 tick 的写法:那是为了让人眼看清 LED 翻转,
 * 但对内核来说 tick 太慢会导致"睡了 0.9 秒的任务也得等满 1 秒才醒",
 * 实时性无从谈起。LED 闪得慢是**任务自己的 delay(500)** 该管的事。*/
#define CFG_TICK_HZ            1000

/* CPU 主频。这份代码不做时钟初始化,直接用复位默认的 HSI 16MHz。
 * 主线里若改了 PLL,这里要跟着改,否则 SysTick 的节拍就不准了。*/
#define CFG_CPU_HZ             16000000u

/* ===================================  ========================================
 * 三、中断与临界区
 * =========================================================================*/

/* 临界区用 BASEPRI 屏蔽到这个值:优先级数值 >= 0x10 的中断全部被挡住,
 * 只剩优先级 0 的中断还能进来(通常不给任何外设用 0,所以等于全屏蔽)。
 *
 * 这里**不能**写 0xFF —— 这是新手最容易踩的坑,展开说:
 *   1) STM32F4 只实现了优先级寄存器的高 4 位,可用的优先级值是
 *      0x00 / 0x10 / 0x20 ... 0xF0,写 0xFF 读回来是 0xF0;
 *   2) BASEPRI 的规则是"优先级数值 **大于等于** BASEPRI 的中断被屏蔽";
 *   3) 于是 BASEPRI = 0xFF 时,最高才 0xF0 的中断全都"小于 0xFF",一个都挡不住。
 * 想留几个高优先级中断不受内核临界区影响(比如电机 PWM),就把它们配成
 * 优先级 0x00,再把这里改成 0x20 —— 0x00 的中断照样能打断临界区。
 * 详细说明见 src/port.c 的 port_enter_critical()。*/
#define CFG_BASEPRI_MASK       0x10

/* PendSV 和 SysTick 的异常优先级,都是最低档。
 * 只实现高 4 位,所以 0xFF 实际落成 0xF0;
 * 关键是**必须是最低**,原因见 src/port.c 的 PendSV_Handler 说明。*/
#define CFG_PENDSV_PRIO        0xFF
#define CFG_SYSTICK_PRIO       0xFF



/* ===========================================================================
 * 四、调试开关
 * =========================================================================*/

#define CFG_ASSERT_ENABLE      1
#define CFG_STACK_CHECK        1

/* 最小断言:条件不成立就停在这里,方便在调试器里看调用栈。
 *
 * 注意 `CFG_ASSERT_ENABLE &&` 而不是 `#if CFG_ASSERT_ENABLE` ——
 * 这是全内核"不写条件编译"的规矩:关掉它只是让这个判断永远为假,
 * 代码依然在,你读到的就是实际会跑的东西。
 *
 * stage4 会把它升级成能报"文件名:行号"的版本,并接到 HardFault 现场解析上。*/
#define KERNEL_ASSERT(cond)                                        \
    do {                                                           \
        if (CFG_ASSERT_ENABLE && !(cond))                          \
        {                                                          \
            debug_assert_failed(__FILE__, __LINE__);               \
        }                                                          \
    } while (0)


/* 创建任务时,把整块栈灌成这个模式;切换时检查最深的几个字有没有被踩。
 * 0xA5A5A5A5 是 FreeRTOS 用的模式值,习惯上跟着用。*/
#define CFG_STACK_FILL_PATTERN 0xA5A5A5A5u

/* 栈溢出判定阈值:栈底(低地址端)这几个字还是填充模式 => 没踩到底;
 * 一旦被改写,说明栈曾经越过这里,报错。*/
#define CFG_STACK_CHECK_WORDS  8



#endif //RTOS_KERNEL_CFG_H
